/** 随机取一句，尽量不连着重复上一句 */
export function pickPhrase(key, last = '') {
  const list = PHRASES[key]
  if (!list || !list.length) return ''
  if (list.length === 1) return list[0]
  for (let i = 0; i < 6; i++) {
    const s = list[Math.floor(Math.random() * list.length)]
    if (s !== last) return s
  }
  return list[0]
}
