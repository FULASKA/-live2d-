/**
 * 预设台词（大肥鱼 · 二创性格）。
 *
 * 基调：灵动、可爱、带点憨憨——话短、语气轻，偶尔嘴硬但立刻软下来；
 * 不用敬语、不长篇大论（长句会把漫画气泡撑爆，也让角色失去「随手一甩」的轻快感）。
 *
 * key 由调用方给：状态（thinking/working/…）或互动（head/hand/pinch）。
 * 同一档每次随机换一句，尽量不连着重复。
 */

export const PHRASES = {
  // 空闲：偶尔冒一句，不吵
  idle: ['在的呀。', '嗯？叫我吗？', '我在这儿哦。', '咦，你来了呀。', '今天也要加油鸭。', '有点困了…'],

  thinking: ['让我想想……', '嗯…脑袋转一下。', '唔，先理一理。', '等一下下，在想呢。', '这个…有点绕。'],
  working: ['在做了在做了。', '手上正忙着呢。', '这一步交给我。', '马上就好哦。', '嘿咻…'],
  waiting: ['要你点个头才行呀。', '这里得你确认一下。', '你看这样可以吗？', '等你一下下。', '唔…卡在这里了。'],
  success: ['做好啦！', '搞定～', '收工收工。', '你看，完成啦。', '嘿嘿，拿下。'],
  error: ['呜…出了点状况。', '这里卡住了呢。', '要重来一次吗？', '坏了坏了。', '不是我干的…大概是。'],

  // 互动
  head: ['头发要乱啦。', '摸头会变笨的。', '别一直摸呀…', '嘿嘿，舒服。', '再摸就咬你哦。'],
  hand: ['手在这里哦。', '要牵手吗？', '别捏啦。', '嗯？怎么了？'],
  pinch: ['脸要变形了！', '呜…轻一点。', '别捏呀！', '要漏气了要漏气了。'],
}

/** 随机取一句，尽量不连着重复上一句 */
export function pickPhrase(key, last = '') {
  const list = PHRASES[key]
  if (!list || !list.length) return ''
  if (list.length === 1) return list[0]
  for (let i = 0; i < 6; i++) {
    const s = list[Math.floor(Math.random() * list.length)]
    if (s !== last) return s
  }
  return list[0]
}
